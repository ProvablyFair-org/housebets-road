import { randomBytes } from 'node:crypto';
import { readFileSync, existsSync, writeFileSync, appendFileSync, renameSync } from 'node:fs';

export const ORIGIN = 'https://www.housebets.com';

// ── client seeds: CSPRNG, every one logged with its source ───────────────────
export const CLIENT_SEED_SOURCE = 'node:crypto randomBytes(16) hex';
export const CLIENT_SEED_FORMAT = '<phase-family prefix><32 lowercase hex chars = 128 random bits>';
/**
 * prefix + 32 hex chars from crypto.randomBytes(16). The prefix only names the phase family; the
 * 128 random bits make the seed unpredictable. `log` (an array, normally meta.clientSeedLog) gets
 * { clientSeed, source, prefix, generatedAt } so each epoch can state where its seed came from.
 */
export function csprngClientSeed(prefix, log, rng = randomBytes) {
  if (typeof prefix !== 'string' || !prefix) throw new Error('csprngClientSeed: prefix required');
  const clientSeed = prefix + rng(16).toString('hex');
  if (Array.isArray(log)) log.push({ clientSeed, prefix, source: CLIENT_SEED_SOURCE, generatedAt: new Date().toISOString() });
  return clientSeed;
}
export const clientSeedSourceOf = (log, clientSeed) =>
  ((Array.isArray(log) ? log : []).find((e) => e.clientSeed === clientSeed) || {}).source || 'not generated by this run';

// ── credential / PII scrubbing ───────────────────────────────────────────────
//  Credential keys: the value is replaced whatever it is. PII keys: personal fields (email, username,
//  platform ids) are scrubbed from any response that carries them; the uuid `id`/`userId` is kept (it is in the
//  dataset already and is not a credential).
const CREDENTIAL_KEY = /^(x-?token|token|access_?token|refresh_?token|id_?token|selector_?token|authorization|cookie|set-cookie|password|passwd|secret|client_?secret|jwt|session|session_?id|api_?key)$/i;
const PII_KEY = /^(email|username|platform_user_id|platformUserId|platformUid|logo|iconUrl|phone|ip|ipAddress)$/i;
const JWT_RE = /eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]*/g;
export const SCRUBBED = '[scrubbed]';

export function scrub(value, path = []) {
  if (value == null) return value;
  if (typeof value === 'string') {
    if (/__Secure-hg-refresh|cf_clearance=/.test(value)) return SCRUBBED;
    return value.replace(JWT_RE, '[scrubbed-jwt]');
  }
  if (Array.isArray(value)) return value.map((v, i) => scrub(v, path.concat(i)));
  if (typeof value === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(value)) {
      if (CREDENTIAL_KEY.test(k) || PII_KEY.test(k)) { out[k] = v == null || v === '' ? v : SCRUBBED; continue; }
      out[k] = scrub(v, path.concat(k));
    }
    return out;
  }
  return value;
}

/** Patterns that must never appear in a written file. Returns the names of those found. */
export function findCredentialLeaks(text) {
  const s = String(text);
  const hits = [];
  if (new RegExp(JWT_RE.source).test(s)) hits.push('jwt');
  if (/__Secure-hg-refresh/.test(s)) hits.push('hg-refresh-cookie');
  if (/cf_clearance/.test(s)) hits.push('cf_clearance');
  // a credential-named JSON key whose value is anything but null / "" / the scrub marker
  const keyRe = /"(x-?token|token|access_?token|refresh_?token|selector_?token|authorization|cookie|set-cookie|password|secret|jwt|session|api_?key)"\s*:\s*("(?!\[scrubbed\])[^"]+"|[{[0-9tf])/gi;
  let m; while ((m = keyRe.exec(s))) hits.push(`key:${m[1]}`);
  return [...new Set(hits)];
}
export function assertNoCredentials(text, where = 'output') {
  const hits = findCredentialLeaks(text);
  if (hits.length) throw new Error(`REFUSING TO WRITE ${where}: credential pattern(s) found: ${hits.join(', ')}`);
}
export function writeJsonSafe(file, obj) {
  const text = JSON.stringify(obj, null, 2);
  assertNoCredentials(text, file);
  writeFileSync(file + '.tmp', text);   // atomic: a kill mid-write can never leave a truncated checkpoint
  renameSync(file + '.tmp', file);
}
export function appendJsonlSafe(file, obj) {
  const line = JSON.stringify(obj);
  assertNoCredentials(line, file);
  appendFileSync(file, line + '\n');
}

// ── auth (refresh-cookie mechanism, identical to the earlier rigs) ───────
export const jwtBody = (t) => { try { return JSON.parse(Buffer.from(String(t).split('.')[1], 'base64').toString()); } catch { return {}; } };
export const ttl = (t, nowSec = Math.floor(Date.now() / 1e3)) => (jwtBody(t).exp || 0) - nowSec;

export function parseCurl(text) {
  let cookie = null;
  let m = text.match(/-b\s+'([^']*)'|--cookie\s+'([^']*)'|-b\s+"([^"]*)"|--cookie\s+"([^"]*)"/);
  if (m) cookie = m[1] || m[2] || m[3] || m[4];
  if (!cookie) { m = text.match(/-H\s+'cookie:\s*([^']*)'|-H\s+"cookie:\s*([^"]*)"/i); if (m) cookie = m[1] || m[2]; }
  const uaM = text.match(/-H\s+'user-agent:\s*([^']*)'|-H\s+"user-agent:\s*([^"]*)"/i);
  const ua = uaM ? (uaM[1] || uaM[2]).trim() : 'Mozilla/5.0';
  return { cookie, ua };
}

export function loadAuth(path) {
  if (!existsSync(path)) throw new Error(`No ${path} — Copy-as-cURL the POST /_api/housegames/refresh request into it (pbpaste > ${path})`);
  const { cookie, ua } = parseCurl(readFileSync(path, 'utf8'));
  if (!cookie) throw new Error('refresh.curl has no cookie — re-copy the /_api/housegames/refresh request as cURL');
  const m = cookie.match(/__Secure-hg-refresh-v2-[0-9a-f]+=v1\.[^.]+\.([A-Za-z0-9._-]+)/);
  if (!m) throw new Error('No __Secure-hg-refresh-v2 cookie in refresh.curl — wrong request. Copy the /_api/housegames/refresh one (Network filter "refresh").');
  const refreshJwt = m[1];
  const life = ttl(refreshJwt);
  if (life < 120) throw new Error(`refresh cookie JWT expired/stale (ttl ${life}s) — re-copy a fresh refresh.curl`);
  return { cookie, ua, refreshJwt, life };
}

/**
 * HTTP client. Endpoints (all confirmed live by the delivered captures — dice v2 on 2026-08-13 and
 * blackjack on 2026-07-20 — except where the calling rig says UNCONFIRMED):
 *   GET  /housegames/seeds?gameType=<g>   → { seed: { id, clientSeed, hashedServerSeed, hashedNextServerSeed, nonce, … } }
 *   POST /housegames/change_seed {gameType, clientSeed} → { oldServerSeed, seed }
 *   POST /housegames/<g>/bet · POST /housegames/<g>/event · GET /housegames/<g>/game
 * Errors carry .status and a SCRUBBED .json; response headers are never kept.
 */
export function makeClient({ cookie, ua, refreshJwt }, game) {
  let token = null, userId = null;
  const base = () => ({ accept: 'application/json', 'user-agent': ua, origin: ORIGIN, referer: `${ORIGIN}/games/housegames-${game}`, cookie });
  async function refresh() {
    const r = await fetch(`${ORIGIN}/_api/housegames/refresh`, { method: 'POST',
      headers: { ...base(), 'content-type': 'application/json' },
      body: JSON.stringify({ apiUrl: `${ORIGIN}/housegames`, intent: 'refresh', token: refreshJwt, selectorToken: refreshJwt }) });
    const t = await r.text(); let j; try { j = JSON.parse(t); } catch { throw new Error(`refresh non-JSON ${r.status}`); }
    if (r.status !== 200 || !j.token) throw new Error(`refresh ${r.status} — re-grab refresh.curl (cookie may be stale)`);
    token = j.token; userId = jwtBody(token).id;
    return true;   // never hand the token back to a caller that might log it
  }
  const ensure = async () => { if (!token || ttl(token) < 60) await refresh(); };
  async function raw(method, path, body) {
    await ensure();
    const r = await fetch(`${ORIGIN}${path}`, { method, headers: { ...base(), 'content-type': 'application/json', 'x-token': token }, body: body ? JSON.stringify(body) : undefined });
    const t = await r.text(); let j;
    try { j = JSON.parse(t); } catch { const e = new Error(`${method} ${path} ${r.status} non-JSON: ${scrub(t.slice(0, 140))}`); e.status = r.status; throw e; }
    if (r.status === 401) { token = null; const e = new Error(`${method} ${path} 401`); e.status = 401; e.json = scrub(j); throw e; }
    if (r.status !== 200) { const e = new Error(`${method} ${path} ${r.status}: ${JSON.stringify(scrub(j)).slice(0, 160)}`); e.status = r.status; e.json = scrub(j); throw e; }
    return j;
  }
  return {
    refresh, ensure, get userId() { return userId; }, get tokenTtl() { return token ? ttl(token) : 0; },
    seedsRaw: () => raw('GET', `/housegames/seeds?gameType=${game}`),
    seeds: async () => (await raw('GET', `/housegames/seeds?gameType=${game}`)).seed,
    rotate: (clientSeed) => raw('POST', '/housegames/change_seed', { gameType: game, clientSeed }),
    bet: (body) => raw('POST', `/housegames/${game}/bet`, body),
    event: (body) => raw('POST', `/housegames/${game}/event`, body),
    gameState: async () => { try { return await raw('GET', `/housegames/${game}/game`); } catch { return null; } },
  };
}

// ── misc pure helpers ────────────────────────────────────────────────────────
export const dig = (o, ...ks) => { for (const k of ks) { const v = k.split('.').reduce((a, kk) => (a == null ? a : a[kk]), o); if (v !== undefined) return v; } return undefined; };
export const commitOf = (seedObj) => (seedObj ? (seedObj.hashedServerSeed ?? seedObj.hashedSeed ?? null) : null);
export const nextCommitOf = (seedObj) => (seedObj ? (seedObj.hashedNextServerSeed ?? seedObj.nextHashedServerSeed ?? null) : null);

/**
 * "Client seed drawn after commitment" witness for ONE epoch E.
 * committedHash = the hash of epoch E's OWN server seed as published BEFORE E's client seed was drawn, i.e.
 * the previous epoch's hashedNextServerSeed (for epoch 0: the pre-capture record's hashedNextServerSeed),
 * read from the operator immediately before the seed is generated. NOT the previous epoch's active hash.
 */
export function commitmentWitness({ committedHash, source, readAt, clientSeed, clientSeedDrawnAt }) {
  return { committedHash: committedHash ?? null, committedHashSource: source, commitmentReadAt: readAt ?? null, clientSeed, clientSeedDrawnAt: clientSeedDrawnAt ?? null };
}
/** Bind a witness to the epoch it belongs to: the published hash must BE the epoch's commitment, and it was read before the seed was drawn. */
export function checkWitness(w, epochHashedServerSeed) {
  if (!w) return { committedHash: null, committedHashSource: 'not recorded', equalsEpochHash: null, readBeforeDraw: null };
  const readBeforeDraw = w.commitmentReadAt && w.clientSeedDrawnAt ? Date.parse(w.commitmentReadAt) <= Date.parse(w.clientSeedDrawnAt) : null;
  return { ...w, equalsEpochHash: w.committedHash == null ? null : w.committedHash === epochHashedServerSeed, readBeforeDraw };
}
export const drawnAtOf = (log, clientSeed) => ((Array.isArray(log) ? log : []).find((e) => e.clientSeed === clientSeed) || {}).generatedAt || null;

/**
 * Shape the pre-capture anchor record. `before` = the active seed pair read BEFORE the first rotation,
 * `after` = the pair read after it (epoch 0). anchorOk is null when the operator exposed no next-hash
 * (never filled in), else whether the next-hash published before epoch 0 IS epoch 0's commitment.
 */
export function buildPreCapture({ before, rawSeedsBefore, recordedAt, oldServerSeed, commitVerified, after, rotateResponseSeed, clientSeedUsed, clientSeedSource }) {
  const nextHashBeforeEpoch0 = nextCommitOf(before);
  const epoch0Commit = commitOf(after);
  return {
    at: recordedAt,
    seedId: before ? before.id ?? null : null,
    clientSeed: before ? before.clientSeed ?? null : null,
    hashedServerSeed: commitOf(before),
    hashedNextServerSeed: nextHashBeforeEpoch0,
    nonceAtRecord: before ? before.nonce ?? null : null,
    rawSeedsBefore: scrub(rawSeedsBefore ?? null),
    revealedServerSeed: oldServerSeed ?? null,
    commitVerified,
    rotatedWithClientSeed: clientSeedUsed ?? null,
    rotatedWithClientSeedSource: clientSeedSource ?? null,
    rotateResponseSeed: scrub(rotateResponseSeed ?? null),
    epoch0SeedId: after ? after.id ?? null : null,
    epoch0HashedServerSeed: epoch0Commit,
    rotateResponseMatchesEpoch0: rotateResponseSeed ? commitOf(rotateResponseSeed) === epoch0Commit : null,
    anchorOk: nextHashBeforeEpoch0 == null ? null : nextHashBeforeEpoch0 === epoch0Commit,
  };
}
